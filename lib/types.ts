  where?: string;
  scenario?: string;
  /** Plain-language rulebooks: how Red decided before, how Green decides now. Puzzles are reasoned out from these. */
  rules?: { old: string[]; new: string[] };
  component: { name: string; what: string; file: string };
  lines: { add: string; del: string };
  /** Missing on older puzzles: logic. */
  family?: PuzzleFamily;
  /** Mixed puzzles: both kinds, primary first (e.g. ["numeric", "visual"]); their data and steps are both present. */
