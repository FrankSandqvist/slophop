/** Puzzle shapes shared by server and client. Gemini only fills these in; all UI is ours. */

export type Tone = "good" | "bad" | "neutral";
/**
 * How an input behaves, which picks its control:
 * toggle = exactly two values (on/off, yes/no) -> a switch; scale = ordered values (low to high) -> a slider;
 * choice = unordered categories -> a tap-to-cycle tile.
 */
export type InputKind = "toggle" | "scale" | "choice";
export type PuzzleInput = {
  id: string;
  label: string;
  kind?: InputKind;
  /** What this condition means in the scene. */
  explain?: string;
  /** `story` is a short phrase for this value in the scene ("your mouse drifted off the card"). */
  values: Array<{ id: string; label: string; story?: string }>;
};
export type PuzzleOutcome = { id: string; label: string; tone: Tone };

/** One combination of input values, with what the code did before (Red) and after (Green) the change. */
export type PuzzleRow = { key: string; values: string[]; old: string; new: string };

/**
 * Rounds are generated by our code from the table, never by the model.
 * Every round is ONE decision that fits the bottom screen; no hunting through controls.
 */
export type Round =
  /** Given a case, guess what Green (side "new") or Red (side "old") does. */
  | { kind: "predict"; row: string; side: "new" | "old" }
  /** Given a case and one outcome, who produced it: Red (old) or Green (new)? */
  | { kind: "who"; row: string; shown: "old" | "new" }
  /** From a base case, which ONE tweak makes Red and Green disagree (or Green reach `target`)? */
  | { kind: "tweak"; base: string; goal: "disagree" | "outcome"; target?: string; options: string[]; answer: string }
  /** A few solved examples, then a mystery case: what does Green do? */
  | { kind: "pattern"; examples: string[]; row: string }
  /** Along an ordered condition, where does Green change its mind? `rows` in value order; the flip is between flip-1 and flip. */
  | { kind: "edge"; input: number; rows: string[]; flip: number }
  /** Odd one out: three cases end the same way with Green, one doesn't. */
  | { kind: "odd"; rows: string[]; odd: string }
  /** Finish Green's rule: "when <input> is ___, I always end at <outcome>". `answers` are all the values that make it true. */
  | { kind: "rule"; input: number; outcome: string; answers: string[] }
  /** In this case only one condition decides what Green does: which? */
  | { kind: "pivot"; row: string; input: number }
  /** Red makes a claim about Green; true or false? `counter` is a row that disproves it. */
  | { kind: "claim"; input: number; value: string; outcome: string; truth: boolean; counter: string | null }
  /* Numbers: worked out from the rules and keyed in, or found along the number line. */
  /** At input x, what number does Green (or Red) give? Keyed in on the keypad. */
  | { kind: "num-predict"; x: number; side: "new" | "old" }
  /** At input x, how much more (or less) does Green give than Red? Keyed in. */
  | { kind: "num-diff"; x: number }
  /** Along the number line, drag to the first input where Green starts to differ from Red. `answer` is that x. */
  | { kind: "num-split"; answer: number }
  /** Drag to the smallest input where Green's result reaches `target`. */
  | { kind: "num-reach"; target: number; answer: number }
  /* Looks: the before/after mock screen in one situation. */
  /** Tap the part of Green's picture that changed. */
  | { kind: "vis-spot"; state: string }
  /** Two pictures of the same situation: which one is Green's? `greenFirst` says which side it's on. */
  | { kind: "vis-which"; state: string; greenFirst: boolean };

/** What a puzzle is about: a decision (logic), a calculation (numeric) or how something looks (visual). */
export type PuzzleFamily = "logic" | "numeric" | "visual";

/** Numbers: Red's and Green's calculation over one real input, sampled by Gemini running Python. */
export type NumericModel = {
  input: { label: string; unit: string; explain: string; min: number; max: number; step: number };
  output: { label: string; unit: string; explain: string; decimals: number };
  /** Everything else held fixed, in plain words. */
  context: string;
  /** Sorted by x; `old` is Red's result, `new` Green's. */
  points: Array<{ x: number; old: number; new: number }>;
};

/** One element of a mock screen, in frame pixels. Drawn by our own MockScreen in the pixel style. */
export type MockShape = { id: string; kind: "box" | "text" | "line"; x: number; y: number; w: number; h: number; fill?: string; stroke?: string; text?: string; color?: string };
/** One situation (a narrow phone, a very long name...): the same screen before (Red) and after (Green). `changed` = ids that differ. */
export type VisualState = { id: string; label: string; story: string; before: MockShape[]; after: MockShape[]; changed: string[] };
/** Looks: a small screen in a few situations. Gemini describes it as data; we draw it. */
export type VisualModel = { frame: { w: number; h: number }; states: VisualState[] };

export type Puzzle = {
  format: number;
  id: string;
  createdAt: string;
  /** `madeWith`: the AI coding tool the PR's own signature names (never guessed); null when it has none. */
  pr: { url: string; repository: string; number: number; title: string; author: string; mergedAt: string | null; madeWith?: string | null };
  /** The PRs the designer chose from. */
  candidates: Array<{ repository: string; number: number; title: string; url: string }>;
  pickReason: string;
  title: string;
  project: string;
  change: string;
  /** Where in the software this code lives, and the scene the puzzle plays in. */
  where?: string;
  scenario?: string;
  /** Plain-language rulebooks: how Red decided before, how Green decides now. Puzzles are reasoned out from these. */
  rules?: { old: string[]; new: string[] };
  component: { name: string; what: string; file: string };
  lines: { add: string; del: string };
  /** Missing on older puzzles: logic. */
  family?: PuzzleFamily;
  /** Logic puzzles: conditions, outcomes and the full truth table. Empty for the other families. */
  inputs: PuzzleInput[];
  outcomes: PuzzleOutcome[];
  table: PuzzleRow[];
  numeric?: NumericModel;
  visual?: VisualModel;
  rounds: Round[];
  /** The real diff lines behind the component, cut from the PR on the server. */
  code: { file: string; lines: string[] } | null;
  /** Two Gemini-designed props for the stage, built from primitives in the PS1 style. */
  props?: PropSpec[];
  /** The Gemini-written, project-specific part of the music prompt. */
  musicStyle?: string;
  /** The tempo Lyria was asked for (chosen per project); the mascots dance to it. */
  bpm?: number;
  /** A 15s PS1-style cutscene about the change (Gemini Omni Flash) and the dialogue lines timed to it. */
  fmv?: { file: string; lines: FmvLine[] } | null;
  musicFile: string | null;
  models: { design: string; music: string | null };
};

/** A low-poly prop, designed by Gemini as primitives and rendered by our PS1 stage. Coordinates: base at y=0, about 1 unit tall. */
/** One line of the cutscene's dialogue: shown in the text box from second `at`. */
export type FmvLine = { at: number; who: "add" | "del" | "narrator"; text: string };

export type PropPart = {
  shape: "box" | "cylinder" | "sphere" | "cone" | "torus";
  color: string;
  position: [number, number, number];
  /** box: width, height, depth · cylinder/cone: radius, height, - · sphere: radius, -, - · torus: radius, tube, - */
  size: [number, number, number];
  rotation: [number, number, number];
};
export type PropSpec = { name: string; parts: PropPart[] };

/** A fetched PR as shown on the stage while a puzzle is being made. */
export type StageCard = { repository: string; number: number; title: string; additions: number; deletions: number; lines: string[]; score?: number };

/** Crowd votes per row: does Green's (new) behaviour seem right here? */
export type VoteTally = Record<string, { right: number; off: number }>;

export const rowKey = (values: string[]) => values.join("~");

export function findRow(puzzle: Puzzle, values: string[]) {
  const key = rowKey(values);
  return puzzle.table.find((row) => row.key === key);
}

export function outcome(puzzle: Puzzle, id: string) {
  return puzzle.outcomes.find((entry) => entry.id === id);
}

export function inputKind(input: PuzzleInput): InputKind {
  if (input.kind === "toggle" && input.values.length === 2) return "toggle";
  if (input.kind === "scale" && input.values.length >= 2) return "scale";
  return "choice";
}

/** The row a round's crowd vote is about. */
export function voteRow(puzzle: Puzzle, round: Round, fallback?: PuzzleRow) {
  const byKey = (key: string | null | undefined) => (key ? puzzle.table.find((row) => row.key === key) : undefined);
  switch (round.kind) {
    case "predict":
    case "who":
    case "pivot":
    case "pattern":
      return byKey(round.row);
    case "tweak":
      return byKey(round.answer);
    case "odd":
      return byKey(round.odd);
    case "edge":
      return byKey(round.rows[round.flip]);
    case "rule":
      return puzzle.table.find((row) => round.answers.includes(row.values[round.input])) ?? fallback;
    case "claim":
      return byKey(round.counter) ?? fallback;
    default:
      return fallback;
  }
}

/** The one input that differs between two rows (for "what if…" tweaks). */
export function changedInput(a: PuzzleRow, b: PuzzleRow) {
  return a.values.findIndex((value, index) => value !== b.values[index]);
}

/** A case told as a little story: "your mouse drifted off the card, nothing's dragged and a menu is open". */
export function storyOf(puzzle: Puzzle, row: PuzzleRow) {
  const parts = row.values.map((valueId, index) => {
    const input = puzzle.inputs[index];
    const value = input?.values.find((entry) => entry.id === valueId);
    return value?.story || `${input?.label.toLowerCase()} is ${value?.label ?? valueId}`;
  });
  return parts.length > 1 ? `${parts.slice(0, -1).join(", ")} and ${parts[parts.length - 1]}` : parts[0] ?? "";
}

export function valueLabel(puzzle: Puzzle, inputIndex: number, valueId: string) {
  return puzzle.inputs[inputIndex]?.values.find((value) => value.id === valueId)?.label ?? valueId;
}

/* ---------- Numbers and looks: a vote is about one input value or one situation ---------- */

/** Rounds to the output's decimals (avoids 0.1 + 0.2 noise in answers). */
export function roundTo(value: number, decimals: number) {
  const factor = 10 ** decimals;
  return Math.round(value * factor) / factor;
}

/** "1 250 kr", "3.5 s": a number with its unit, at the given decimals. */
export function formatNumber(value: number, unit: string, decimals = 0) {
  const text = roundTo(value, decimals).toLocaleString("en-US", { minimumFractionDigits: decimals, maximumFractionDigits: decimals });
  if (!unit) return text;
  return /^[$€£¥]$/.test(unit) ? `${value < 0 ? "-" : ""}${unit}${text.replace("-", "")}` : `${text} ${unit}`;
}

export function pointAt(model: NumericModel, x: number) {
  return model.points.find((point) => point.x === x);
}

/** A vote row for a number puzzle: one input value, with Red's and Green's results. */
export function numericRow(model: NumericModel, x: number): PuzzleRow {
  const point = pointAt(model, x);
  return { key: `x~${x}`, values: [String(x)], old: String(point?.old ?? ""), new: String(point?.new ?? "") };
}

/** A vote row for a looks puzzle: one situation. */
export function visualRow(state: VisualState): PuzzleRow {
  return { key: `state~${state.id}`, values: [state.id], old: "before", new: "after" };
}

/** Human label for a vote key of any family (for "where players doubt Green"). */
export function caseLabel(puzzle: Puzzle, key: string) {
  if (key.startsWith("x~") && puzzle.numeric) {
    const x = Number(key.slice(2));
    const { input, output } = puzzle.numeric;
    const point = pointAt(puzzle.numeric, x);
    return `${input.label} ${formatNumber(x, input.unit)}${point ? ` → Green ${formatNumber(point.new, output.unit, output.decimals)}, Red ${formatNumber(point.old, output.unit, output.decimals)}` : ""}`;
  }
  if (key.startsWith("state~") && puzzle.visual) return puzzle.visual.states.find((state) => `state~${state.id}` === key)?.label ?? key;
  return null;
}
